import { store, events, reloads, sleep, ok, done } from './env.js';
const sync = await import('../src/sync.js');
const sb = await import('../src/supabase.js');
const { clearAccountData } = await import('../src/utils/accounts.js');
const cloud = () => globalThis.__cloud;
const upserts = () => cloud().calls.filter(c => c[0] === 'upsert' && !String(c[1].key || '').startsWith('__status:')).length;
const cloudVal = (k) => cloud().rows.find(r => r.key === k)?.value;
let t = Date.parse('2027-01-01');
const cloudSet = (key, value) => {
  cloud().rows = cloud().rows.filter(r => r.key !== key);
  cloud().rows.push({ user_id: 'user-1', key, value, updated_at: new Date(t += 1000).toISOString() });
};
cloud().rows = [];
cloudSet('todos', [{ id: 1, text: 'a' }]);
cloudSet('sidebarOrder', [{ id: 'dashboard', label: 'Old label' }]);
cloudSet('theme', 'dark');
store.todos = JSON.stringify([{ id: 1, text: 'stale local' }]);
console.log('\n--- startup ---');
ok('startup pull succeeded', (await sync.startupSync()) === true);
ok('opens on the cloud copy', JSON.parse(store.todos)[0].text === 'a');
console.log('\n--- re-saves are not edits ---');
let before = upserts();
localStorage.setItem('todos', JSON.stringify([{ id: 1, text: 'a' }]));
localStorage.setItem('theme', 'dark');
await sleep(900);
ok('no push', upserts() === before);
console.log('\n--- sidebarOrder goes up once, then rests ---');
before = upserts();
localStorage.setItem('sidebarOrder', JSON.stringify([{ id: 'dashboard', label: 'Dashboard' }]));
await sleep(900);
ok('pushed once', upserts() === before + 1);
const reh = [];
const stop = sync.startPolling((k) => reh.push(k), 200);
await sleep(700);
ok('polling finds nothing', events.length === 0 && reh.length === 0 && reloads.n === 0);
console.log('\n--- hot key from elsewhere ---');
cloudSet('todos', [{ id: 1, text: 'a' }, { id: 2, text: 'from mac' }]);
await sleep(700);
ok('re-read in place', reh.includes('todos') && JSON.parse(store.todos).length === 2 && reloads.n === 0);
before = upserts();
localStorage.setItem('todos', JSON.stringify([{ id: 1, text: 'a' }, { id: 2, text: 'from mac' }]));
await sleep(900);
ok('echo not pushed', upserts() === before);
console.log('\n--- an App setting from elsewhere is applied in place ---');
cloudSet('theme', 'light');
await sleep(700);
ok('theme re-read into state', reh.includes('theme'));
console.log('\n--- a section-owned key from elsewhere ---');
cloudSet('goals', ['from mac']);
await sleep(700);
ok('stored and announced', events.includes('goals') && JSON.parse(localStorage.getItem('goals'))[0] === 'from mac');
before = upserts();
localStorage.setItem('goals', JSON.stringify(['written here']));
await sleep(900);
ok('a write here is sent, never held', upserts() === before + 1 && JSON.stringify(cloudVal('goals')) === '["written here"]');
await sleep(4000);
ok('and the window is never reloaded', reloads.n === 0);
stop();
console.log('\n--- in-flight race ---');
localStorage.setItem('goals', JSON.stringify(['v1']));
await sleep(750);
localStorage.setItem('goals', JSON.stringify(['v2']));
await sleep(50);
ok('v2 still marked', sb.readDirtyKeys().has('goals'));
await sleep(900);
ok('v2 lands and mark clears', JSON.stringify(cloudVal('goals')) === '["v2"]' && !sb.readDirtyKeys().has('goals'));
console.log('\n--- account clear leaves the cloud alone ---');
const n = cloud().rows.length;
const deletesBefore = cloud().calls.filter(c => c[0] === 'delete').length;
globalThis.__diag = () => {};
await clearAccountData().catch(() => {});
ok('the clear sent no deletes', cloud().calls.filter(c => c[0] === 'delete').length === deletesBefore);
ok('every row is still there', cloud().rows.length === n);
ok('the device is empty', localStorage.getItem('todos') === null);
done();
