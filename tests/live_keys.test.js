import { store, sleep, ok, done } from './env.js';
const fired = [];
const realDispatch = globalThis.dispatchEvent;
globalThis.dispatchEvent = (e) => { fired.push(e.type + ':' + (e.detail?.key || e.key || '')); return true; };
globalThis.CustomEvent = class { constructor(t, o) { this.type = t; this.detail = o?.detail; } };
globalThis.StorageEvent = class { constructor(t, o) { this.type = t; Object.assign(this, o); } };
const listeners = {};
globalThis.addEventListener = (t, f) => { (listeners[t] ||= []).push(f); };
const sync = await import('../src/sync.js');
const { reloads } = await import('./env.js');
const cloud = () => globalThis.__cloud;
let t = Date.now() - 100000;
const cloudSet = (key, value) => { cloud().rows = cloud().rows.filter(r => r.key !== key); cloud().rows.push({ user_id: 'user-1', key, value, updated_at: new Date(t += 1000).toISOString() }); };
const keys = { notes: [{ id: 1, title: 'a' }], payments_v2: [{ id: 1 }], habitTracker_habits: [{ id: 1 }], meds_v1: [{ id: 1 }], planner_blocks: [{ id: 1 }], kana_stats: { a: 1 } };
cloud().rows = [];
for (const [k, v] of Object.entries(keys)) { cloudSet(k, v); store[k] = JSON.stringify(v); }
await sync.startupSync();
const rehydrated = [];
const stop = sync.startPolling((k) => rehydrated.push(k), 150);
await sleep(300);

console.log('\n--- sections that can refresh themselves are told, and not reloaded ---');
cloudSet('notes', [{ id: 1, title: 'from mac' }]);
cloudSet('payments_v2', [{ id: 1 }, { id: 2 }]);
cloudSet('habitTracker_habits', [{ id: 1 }, { id: 2 }]);
cloudSet('meds_v1', [{ id: 1 }, { id: 2 }]);
cloudSet('planner_blocks', [{ id: 1 }, { id: 2 }]);
await sleep(500);
ok('notes -> notes-updated', fired.includes('notes-updated:notes'));
ok('payments -> storage', fired.includes('storage:payments_v2'));
ok('habits -> habits-updated', fired.includes('habits-updated:habitTracker_habits'));
ok('meds -> meds-changed', fired.includes('meds-changed:meds_v1'));
ok('calendar -> planner-data-changed with its key', fired.includes('planner-data-changed:planner_blocks'));
ok('no reload for any of them', reloads.n === 0);

console.log('\n--- kana practice data changed elsewhere, mid-practice here ---');
cloudSet('kana_selected_rows', ['a', 'ka']);
cloudSet('kana_stats', { a: 2 });
await sleep(500);
ok('it is stored for the next time practice opens', JSON.parse(localStorage.getItem('kana_selected_rows')).includes('ka'));
await sleep(4000);
ok('the window is NOT reloaded out from under the practice', reloads.n === 0);
const before = cloud().calls.filter(c => c[0] === 'upsert' && c[1].key === 'kana_stats').length;
localStorage.setItem('kana_stats', JSON.stringify({ a: 1, answered: true }));
await sleep(900);
ok('the next answer here is saved and sent', cloud().calls.filter(c => c[0] === 'upsert' && c[1].key === 'kana_stats').length === before + 1);
stop();

console.log('\n--- notes merge ---');
const { mergeIncomingNotes } = await import('../src/components/Notes.jsx');
const base = [{ id: 1, content: 'one' }, { id: 2, content: 'two' }];
const incoming = [{ id: 1, content: 'one (mac)' }, { id: 2, content: 'two (mac)' }, { id: 3, content: 'new on mac' }];
let m = mergeIncomingNotes(base, incoming, base, 2);
ok('open but untouched note takes the incoming version', m.find(n => n.id === 2).content === 'two (mac)');
ok('others too, and new notes arrive', m.find(n => n.id === 1).content === 'one (mac)' && m.some(n => n.id === 3));
const edited = [{ id: 1, content: 'one' }, { id: 2, content: 'two + typing here' }];
m = mergeIncomingNotes(edited, incoming, base, 2);
ok('a note being edited here keeps its edit', m.find(n => n.id === 2).content === 'two + typing here');
ok('while every other note updates', m.find(n => n.id === 1).content === 'one (mac)' && m.some(n => n.id === 3));
m = mergeIncomingNotes(edited, [{ id: 1, content: 'x' }], base, 2);
ok('an edited note deleted elsewhere is not lost', m.some(n => n.id === 2 && n.content === 'two + typing here'));
m = mergeIncomingNotes(edited, incoming, base, null);
ok('nothing open: everything takes the incoming version', JSON.stringify(m) === JSON.stringify(incoming));
done();
