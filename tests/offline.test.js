import { store, sleep, ok, done } from './env.js';
const sync = await import('../src/sync.js');
const sb = await import('../src/supabase.js');
const cloudVal = (k) => globalThis.__cloud.rows.find(r => r.key === k)?.value;
globalThis.__cloud.rows = [{ user_id: 'user-1', key: 'todos', value: [{ id: 1, text: 'newer, other machine' }], updated_at: '2027-01-01T00:00:00Z' }];
store.todos = JSON.stringify([{ id: 1, text: 'older, this device' }]);
globalThis.__cloud.failAll = true;
console.log('\n--- offline start ---');
ok('startup reports failure', (await sync.startupSync()) === false);
sync.settleAfterMount();
localStorage.setItem('todos', JSON.stringify([{ id: 1, text: 'older, this device' }]));
ok('mount write is not an edit', !sb.readDirtyKeys().has('todos'));
await sleep(3200);
localStorage.setItem('goals', JSON.stringify(['offline edit']));
ok('later edit is marked', sb.readDirtyKeys().has('goals'));
globalThis.__cloud.failAll = false;
const stop = sync.startPolling(() => {}, 200);
await sleep(900);
stop();
ok('offline edit reaches the cloud', JSON.stringify(cloudVal('goals')) === '["offline edit"]');
ok('newer cloud list not overwritten', cloudVal('todos')[0].text === 'newer, other machine');
ok('and shown here', JSON.parse(store.todos)[0].text === 'newer, other machine');
done();
